import numpy as np

from dataclasses import dataclass, field
from pathlib import Path

# Pulse table format:
PULSE_DTYPE = np.dtype([
    ('MaxHeight', np.int64),
    ('MidHeight', np.int64),
    ('Width', np.int64),
    ('Area', np.int64),
    ('Gain', np.int64),
    ('MaxGainStage', np.int64),
    ('MidGainStage', np.int64),
    ('Flagged', np.bool_),
])

@dataclass
class MultisizerRun:
    '''
    A Beckman Coulter Multisizer run.

    Supported filetypes:
     * .=#Z2 - Z2 AccuComp
     * .#M3 - Multisizer 3

    Run files are .ini-like, with key-value pairs grouped into sections.
    '''
    path: Path
    fields: dict[str, dict[str, str]] = field(default_factory=dict)
    arrays: dict[str, list[str]] = field(default_factory=dict)

def parse_file(path):
    '''
    Parse Multisizer data into 'fields' and 'arrays'.
    '''
    data = MultisizerRun(Path(path))
    section = None

    with data.path.open(encoding='cp1252') as fh:
        lines = [raw.strip() for raw in fh]

    for line in lines:

        # Skip blank lines.
        if not line:
            continue

        # Start a new section.
        if line.startswith('[') and line.endswith(']'):
            section = line[1:-1].strip()
            continue

        if section is None:
            raise ValueError(f'Found data outside of a section: {line!r}')

        # Parse kv pairs.
        key, sep, value = line.partition('=')
        if sep:
            data.fields.setdefault(section, {})[key.strip()] = value.strip()
        else:
            data.arrays.setdefault(section, []).append(line)

    return data

def has_pulses(data):
    '''
    Check if the file holds raw pulse data.
    '''
    return '#Pulses5hex' in data.arrays

def extract_pulses(data):
    '''
    Extract raw pulse data as a structured array (PULSE_DTYPE),
    with columns accessed by name, e.g. pulses['MaxHeight'].

    Pulse5hex fields:
     - MaxHeight
     - MidHeight
     - Width
     - Area
     - Gain

    Gain bit fields:
     - MaxGainStage
     - MidGainStage
     - Flagged
    '''
    if not has_pulses(data):
        raise ValueError('No raw pulse data found.')

    # Decode the pulse fields.
    rows = [
        [int(x, base=16) for x in row.split(',')]
        for row in data.arrays['#Pulses5hex']
    ]
    rows = np.array(rows, dtype=np.int64)

    # Store the pulses as a table.
    pulses = np.zeros(len(rows), dtype=PULSE_DTYPE)
    pulses['MaxHeight'] = rows[:, 0]
    pulses['MidHeight'] = rows[:, 1]
    pulses['Width'] = rows[:, 2]
    pulses['Area'] = rows[:, 3]
    pulses['Gain'] = rows[:, 4]

    # Unpack the Gain bit field.
    gain = pulses['Gain']
    pulses['MaxGainStage'] = gain & 0x0F
    pulses['MidGainStage'] = (gain & 0x70) >> 4
    pulses['Flagged'] = (gain & 0x80) != 0

    return pulses

def extract_diameters(data):
    '''
    Extract diameters from pulses in an m3 file.

    These correspond to the spherical equivalent diameter,
    aka the Heywood diameter.

    Diameters are reported in microns.
    '''
    Instrument = data.fields['instrument']

    Kd = float(Instrument['Kd'])
    MaxHtCorr = int(Instrument['MaxHtCorr'])
    CountsPerVolt = 838861  # 1/V
    Current = int(Instrument['Current']) / 1000  # mA
    Resistance = 25 * int(Instrument['Gain'])  # kohm

    Pulses = extract_pulses(data)
    Height = Pulses['MaxHeight'] + MaxHtCorr
    Diameter = Kd * (Height / (CountsPerVolt * Current * Resistance)) ** (1/3)

    return Diameter

def extract_volumes(data):
    '''
    Extract volumes from pulses in an m3 file.

    Volumes are reported in cubic microns, aka femtoliters.
    '''
    Diameter = extract_diameters(data)
    Volume = np.pi / 6 * Diameter ** 3

    return Volume

def extract_histogram(data):
    '''
    Extract histogram data generated by the Multisizer control software.
    '''
    BinDiameterIter = (float(x) for x in data.arrays['#Bindiam'])
    BinHeightIter = (float(x) for x in data.arrays['#Binheight'])

    BinDiameter = np.fromiter(BinDiameterIter, dtype=float)
    BinHeight = np.fromiter(BinHeightIter, dtype=float)

    return BinDiameter, BinHeight
