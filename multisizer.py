import numpy as np

from dataclasses import dataclass, field
from pathlib import Path

@dataclass
class MultisizerRun:
    '''
    A Beckman Coulter Multisizer 3 run.

    Run files are .ini-like, with key-value pairs grouped into sections.
    '''
    path: Path
    fields: dict[str, dict[str, str]] = field(default_factory=dict)
    arrays: dict[str, list[str]] = field(default_factory=dict)

def parse_M3_file(filename):
    '''
    Parse Multisizer data into 'fields' and 'arrays'.
    '''
    data = MultisizerRun(Path(filename))
    section = None

    with open(filename) as fh:
        lines = [raw.strip() for raw in fh]

    for line in lines:

        # Start a new section.
        if line.startswith('[') and line.endswith(']'):
            section = line[1:-1].strip()
            continue

        # Parse kv pairs.
        key, sep, value = line.partition('=')
        if sep:
            data.fields.setdefault(section, {})[key.strip()] = value.strip()
        else:
            data.arrays.setdefault(section, []).append(line)

    return data

def decode_pulse(pulse_array):
    return [int(n, 16) for n in pulse_array.split(',')]

def extract_pulses(M3_data):
    '''
    Pulse hex format:
    - MaxHeight
    - MidHeight
    - Width
    - Area
    - Gain
    '''
    Pulses = M3_data.arrays['#Pulses5hex']
    return np.array([decode_pulse(p) for p in Pulses])

def extract_diameters(M3_data):
    '''
    Extract diameters from pulses in an m3 file.

    These correspond to the spherical equivalent diameter,
    aka the Heywood diameter.

    Diameters are reported in microns.
    '''
    Instrument = M3_data.fields['instrument']

    Kd = float(Instrument['Kd'])
    MaxHtCorr = int(Instrument['MaxHtCorr'])
    CountsPerVolt = 838861  # 1/V
    Current = int(Instrument['Current']) / 1000  # mA
    Resistance = 25 * int(Instrument['Gain'])  # kohm

    Pulses = extract_pulses(M3_data)
    Height = Pulses[:, 0] + MaxHtCorr
    Diameter = Kd * (Height / (CountsPerVolt * Current * Resistance)) ** (1/3)

    return Diameter

def extract_volumes(M3_data):
    '''
    Extract volumes from pulses in an m3 file.

    Volumes are reported in cubic microns, aka femtoliters.
    '''
    Diameter = extract_diameters(M3_data)
    Volume = np.pi / 6 * Diameter ** 3

    return Volume

def extract_histogram(M3_data):
    '''
    Extract histogram data generated by the Multisizer control software.
    '''
    BinDiameterIter = (float(x) for x in M3_data.arrays['#Bindiam'])
    BinHeightIter = (float(x) for x in M3_data.arrays['#Binheight'])

    BinDiameter = np.fromiter(BinDiameterIter, dtype=float)
    BinHeight = np.fromiter(BinHeightIter, dtype=float)

    return BinDiameter, BinHeight
